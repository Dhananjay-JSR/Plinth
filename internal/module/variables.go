package module

import (
	"fmt"
	"os"
	"path/filepath"
	"slices"

	"github.com/hashicorp/hcl/v2"
	"github.com/hashicorp/hcl/v2/hclsyntax"
)

// VariablesFile is generated into every module copy in a workspace bundle.
const VariablesFile = "plinth_variables.tf"

// Variables declares the four variables Plinth passes to every module, so
// module authors never write them.
const Variables = `# Generated by Plinth: every module receives these four variables. Do not edit.

variable "instance" {
  description = "kind, flavor, version and the effective spec"
  type        = any
}

variable "instance_name" {
  description = "The resource instance's name"
  type        = string
}

variable "environment" {
  description = "The environment, e.g. { name = \"prod\" }"
  type        = any
}

variable "inputs" {
  description = "Connected producers' outputs by input name; null for an unconnected optional input"
  type        = any
}
`

var reserved = []string{"instance", "instance_name", "environment", "inputs"}

// checkReservedVariables rejects a module that declares any of the four
// variables Plinth generates, or ships its own copy of the generated file.
func checkReservedVariables(dir string) error {
	if _, err := os.Stat(filepath.Join(dir, VariablesFile)); err == nil {
		return fmt.Errorf("%s is generated by Plinth; remove it from the module", VariablesFile)
	}
	files, err := filepath.Glob(filepath.Join(dir, "*.tf"))
	if err != nil {
		return err
	}
	var errs []error
	for _, path := range files {
		src, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		f, diags := hclsyntax.ParseConfig(src, filepath.Base(path), hcl.InitialPos)
		if diags.HasErrors() {
			return fmt.Errorf("%s: %s", path, diags.Error())
		}
		for _, b := range f.Body.(*hclsyntax.Body).Blocks {
			if b.Type == "variable" && len(b.Labels) == 1 && slices.Contains(reserved, b.Labels[0]) {
				errs = append(errs, fmt.Errorf("%s: variable %q is provided by Plinth; remove its declaration", filepath.Base(path), b.Labels[0]))
			}
		}
	}
	if len(errs) > 0 {
		return joinSorted(errs)
	}
	return nil
}
