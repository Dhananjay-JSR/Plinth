// Package generate renders an effective configuration into a workspace bundle:
// a plain OpenTofu root (main.tf), copies of every module it uses, and a manifest.
// The same configuration always renders to the same bytes.
package generate

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/Dhananjay-JSR/Plinth/internal/blueprint"
	"github.com/Dhananjay-JSR/Plinth/internal/catalog"
	"github.com/hashicorp/hcl/v2/hclwrite"
)

// Version identifies the generator in manifests; bump it when output changes.
const Version = "plinth-generator/0.1.0"

const ManifestFile = ".plinth/manifest.json"

// Render writes the workspace bundle for cfg into out, which must not exist or be empty.
func Render(cfg *blueprint.Config, out string) error {
	if entries, err := os.ReadDir(out); err == nil && len(entries) > 0 {
		return fmt.Errorf("%s is not empty; refusing to overwrite", out)
	} else if err != nil && !os.IsNotExist(err) {
		return err
	}

	modules := map[string]*catalog.Resolved{}
	var src bytes.Buffer
	src.WriteString("# Generated by Plinth. Do not edit.\n")
	for _, r := range cfg.Instances {
		modules[r.Module.Module.ID()] = r.Module
		src.WriteString(moduleBlock(cfg.Environment, r))
	}
	if err := writeFile(filepath.Join(out, "main.tf"), hclwrite.Format(src.Bytes())); err != nil {
		return err
	}

	ids := make([]string, 0, len(modules))
	for id := range modules {
		ids = append(ids, id)
	}
	slices.Sort(ids)
	for _, id := range ids {
		m := modules[id]
		dst := filepath.Join(out, "modules", filepath.FromSlash(id))
		if err := copyDir(m.Module.Dir, dst); err != nil {
			return err
		}
		// The catalog may have changed since resolution; never ship unpinned content.
		if got, err := catalog.Digest(dst); err != nil {
			return err
		} else if got != m.Digest {
			return fmt.Errorf("module %s changed during render (digest %s, resolved %s)", id, got, m.Digest)
		}
	}

	manifest, err := json.MarshalIndent(buildManifest(cfg, modules), "", "  ")
	if err != nil {
		return err
	}
	return writeFile(filepath.Join(out, filepath.FromSlash(ManifestFile)), append(manifest, '\n'))
}

// CallName is the generated module call name for an instance address <kind>/<name>.
func CallName(addr string) string { return strings.Replace(addr, "/", "__", 1) }

func moduleBlock(env string, r *blueprint.Resolved) string {
	m := r.Module.Module
	inputs := map[string]any{}
	for name, b := range r.Inputs {
		if b == nil {
			inputs[name] = nil
		} else {
			inputs[name] = expr("module." + CallName(b.Producer) + "." + b.Output)
		}
	}
	var b strings.Builder
	fmt.Fprintf(&b, "\nmodule %q {\n", CallName(r.Addr))
	fmt.Fprintf(&b, "source = %q\n", "./modules/"+m.ID())
	fmt.Fprintf(&b, "instance_name = %q\n", r.Name)
	fmt.Fprintf(&b, "instance = %s\n", value(map[string]any{"kind": m.Kind, "flavor": m.Flavor, "version": m.Version, "spec": r.Spec}))
	fmt.Fprintf(&b, "environment = %s\n", value(map[string]any{"name": env}))
	fmt.Fprintf(&b, "inputs = %s\n", value(inputs))
	b.WriteString("}\n")
	return b.String()
}

// expr is a raw HCL expression, emitted without quoting.
type expr string

// value renders a normalized JSON-like value as an HCL expression with sorted keys.
func value(v any) string {
	switch t := v.(type) {
	case nil:
		return "null"
	case expr:
		return string(t)
	case bool, json.Number:
		return fmt.Sprint(t)
	case string:
		return quote(t)
	case []any:
		parts := make([]string, len(t))
		for i, x := range t {
			parts[i] = value(x)
		}
		return "[" + strings.Join(parts, ", ") + "]"
	case map[string]any:
		if len(t) == 0 {
			return "{}"
		}
		keys := make([]string, 0, len(t))
		for k := range t {
			keys = append(keys, k)
		}
		slices.Sort(keys)
		var b strings.Builder
		b.WriteString("{\n")
		for _, k := range keys {
			fmt.Fprintf(&b, "%s = %s\n", quoteLiteral(k), value(t[k]))
		}
		b.WriteString("}")
		return b.String()
	}
	panic(fmt.Sprintf("generate: unexpected value type %T", v)) // specs are normalized before render
}

// quote renders a spec string as an HCL template: Plinth references become
// module output expressions, everything else stays literal.
func quote(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	last := 0
	for _, loc := range blueprint.RefPattern.FindAllStringSubmatchIndex(s, -1) {
		b.WriteString(escape(s[last:loc[0]]))
		ref, err := blueprint.ParseRef(s[loc[2]:loc[3]])
		if err != nil {
			panic(err) // resolution already rejected invalid references
		}
		b.WriteString("${module." + CallName(ref.Addr()) + "." + strings.Join(append([]string{ref.Output}, ref.Path...), ".") + "}")
		last = loc[1]
	}
	b.WriteString(escape(s[last:]))
	b.WriteByte('"')
	return b.String()
}

func quoteLiteral(s string) string { return `"` + escape(s) + `"` }

// escape makes s literal inside an HCL quoted template.
func escape(s string) string {
	var b strings.Builder
	for i, r := range s {
		switch {
		case r == '\\':
			b.WriteString(`\\`)
		case r == '"':
			b.WriteString(`\"`)
		case r == '\n':
			b.WriteString(`\n`)
		case r == '\r':
			b.WriteString(`\r`)
		case r == '\t':
			b.WriteString(`\t`)
		case r < 0x20:
			fmt.Fprintf(&b, `\u%04x`, r)
		case (r == '$' || r == '%') && strings.HasPrefix(s[i+1:], "{"):
			b.WriteRune(r) // "$${" and "%%{" are literal "${" and "%{"
			b.WriteRune(r)
		default:
			b.WriteRune(r)
		}
	}
	return b.String()
}

type manifestModule struct {
	Catalog string `json:"catalog"`
	Digest  string `json:"digest"`
}

type manifest struct {
	Generator       string                    `json:"generator"`
	Environment     string                    `json:"environment"`
	Modules         map[string]manifestModule `json:"modules"`
	EffectiveConfig string                    `json:"effective_config"`
}

func buildManifest(cfg *blueprint.Config, modules map[string]*catalog.Resolved) manifest {
	mf := manifest{Generator: Version, Environment: cfg.Environment, Modules: map[string]manifestModule{}}
	for id, m := range modules {
		mf.Modules[id] = manifestModule{Catalog: m.Catalog, Digest: m.Digest}
	}
	type instance struct {
		Module string                        `json:"module"`
		Digest string                        `json:"digest"`
		Spec   any                           `json:"spec"`
		Inputs map[string]*blueprint.Binding `json:"inputs"`
	}
	eff := map[string]instance{}
	for _, r := range cfg.Instances {
		eff[r.Addr] = instance{r.Module.Module.ID(), r.Module.Digest, r.Spec, r.Inputs}
	}
	b, err := json.Marshal(struct {
		Environment string              `json:"environment"`
		Instances   map[string]instance `json:"instances"`
	}{cfg.Environment, eff}) // map keys marshal sorted, so this is canonical
	if err != nil {
		panic(err) // only normalized JSON values reach here
	}
	sum := sha256.Sum256(b)
	mf.EffectiveConfig = "sha256:" + hex.EncodeToString(sum[:])
	return mf
}

func copyDir(src, dst string) error {
	return filepath.WalkDir(src, func(path string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		if !d.Type().IsRegular() {
			return fmt.Errorf("%s: only regular files are allowed in a module", path)
		}
		rel, err := filepath.Rel(src, path)
		if err != nil {
			return err
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		return writeFile(filepath.Join(dst, rel), data)
	})
}

func writeFile(path string, data []byte) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, data, 0o644)
}
